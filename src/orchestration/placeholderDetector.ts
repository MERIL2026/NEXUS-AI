/**
 * NEXUS AI — Production-Grade Content Substance & Placeholder Detector
 *
 * Provides deterministic, reusable AST & textual analysis over generated web artifacts.
 * Prevents empty skeletons, comment-only containers, unresolved generation tokens,
 * and generic fallback templates from masquerading as successful task completions.
 */

export interface PlaceholderDetectionResult {
  hasPlaceholders: boolean;
  reasons: string[];
  placeholderMatches: string[];
}

export interface SkeletonDetectionResult {
  isSkeleton: boolean;
  totalContainers: number;
  emptyOrCommentOnlyContainers: number;
  skeletonSectionNames: string[];
  reasons: string[];
}

export interface ContentVerificationResult {
  valid: boolean;
  errorCategory?: string;
  reason?: string;
  visibleTextLength?: number;
  detectedBrand?: string;
  foundBrand?: boolean;
  missingSections?: string[];
  skeletonSections?: string[];
}

