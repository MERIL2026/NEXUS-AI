/**
 * Detects unresolved placeholder comments, TODO/TBD markers, and generic templates.
 */
export function detectPlaceholders(htmlContent: string, taskGoal?: string): PlaceholderDetectionResult {
  const reasons: string[] = [];
  const matches: string[] = [];

  const lowerGoal = (taskGoal || '').toLowerCase();

  // Pattern 1: Placeholder comments like <!-- Hero Content -->, <!-- Features Content -->, <!-- Content -->, <!-- TODO -->
  const commentPlaceholderRegex = /<!--\s*([a-zA-Z0-9_\s-]*?(?:\bcontent\b|\btodo\b|\btbd\b|\bplaceholder\b|insert\s+\w+\s+here|your\s+content)[a-zA-Z0-9_\s-]*?)\s*-->/gi;
  let commentMatch: RegExpExecArray | null;
  while ((commentMatch = commentPlaceholderRegex.exec(htmlContent)) !== null) {
    const matchedText = commentMatch[0].trim();
    matches.push(matchedText);
    reasons.push(`Unresolved placeholder comment detected: "${matchedText}"`);
  }

  // Pattern 2: Explicit placeholder text tokens inside visible body text
  const bodyMatch = htmlContent.match(/<body\b[^>]*>([\s\S]*?)<\/body>/i);
  const bodyHtml = bodyMatch ? bodyMatch[1] : htmlContent;
  const visibleBodyText = extractVisibleText(bodyHtml);

  const textTokenPatterns: Array<{ regex: RegExp; name: string; target: 'visible' | 'raw'; allowIfInGoal?: boolean }> = [
    { regex: /\bTODO\b/i, name: 'TODO token', target: 'visible' },
    { regex: /\bTBD\b/i, name: 'TBD token', target: 'visible' },
    { regex: /\bPLACEHOLDER\b/i, name: 'PLACEHOLDER token', target: 'visible' },
    { regex: /\bYOUR\s+CONTENT\s+HERE\b/i, name: 'YOUR CONTENT HERE token', target: 'visible' },
    { regex: /\bINSERT\s+[\w\s]+\s+HERE\b/i, name: 'INSERT ... HERE token', target: 'visible' },
    { regex: /\bREPLACE\s+WITH\s+[\w\s]+\b/i, name: 'REPLACE WITH ... token', target: 'visible' },
    { regex: /\bLorem\s+ipsum\s+dolor\b/i, name: 'Lorem ipsum placeholder text', target: 'visible' },
    {
      regex: /Generated\s+by\s+NEXUS\s+AI\s+Agent/i,
      name: 'Generic fallback marker "Generated by NEXUS AI Agent"',
      target: 'raw',
      allowIfInGoal: lowerGoal.includes('nexus ai agent') || lowerGoal.includes('nexus web application'),
    },
    {
      regex: /NEXUS\s+Web\s+Application/i,
      name: 'Generic fallback title "NEXUS Web Application"',
      target: 'raw',
      allowIfInGoal: lowerGoal.includes('nexus web application'),
    },
  ];

  for (const { regex, name, target, allowIfInGoal } of textTokenPatterns) {
    if (allowIfInGoal) continue;
    const searchTarget = target === 'visible' ? visibleBodyText : htmlContent;
    const match = searchTarget.match(regex);
    if (match) {
      matches.push(match[0]);
      reasons.push(`Unresolved generation marker detected: ${name} ("${match[0]}")`);
    }
  }

  return {
    hasPlaceholders: matches.length > 0,
    reasons,
    placeholderMatches: matches,
  };
}

