/**
 * Extracts candidate brand / proper project names from the task goal.
 */
export function extractBrandCandidates(taskGoal: string): string[] {
  const stopWords = new Set([
    'a', 'an', 'the', 'and', 'or', 'for', 'with', 'to', 'of', 'in', 'on', 'at', 'by', 'as', 'is', 'it',
    'build', 'create', 'make', 'generate', 'implement', 'write', 'complete', 'premium',
    'modern', 'multi-section', 'landing', 'website', 'webpage', 'page', 'fictional',
    'technology', 'company', 'saas', 'app', 'application', 'site', 'dark', 'aesthetic',
    'responsive', 'include', 'including', 'navbar', 'hero', 'features', 'solutions',
    'dashboard', 'testimonials', 'pricing', 'faq', 'cta', 'footer', 'using', 'html',
    'css', 'js', 'javascript', 'typescript', 'folder', 'directory', 'new', 'task', 'test',
    'project', 'demo', 'sample', 'simple', 'basic', 'web', 'file', 'files', 'frontend',
    'backend', 'local', 'preview', 'server', 'code', 'data', 'database', 'system', 'user',
    'run', 'first', 'second', 'third', 'interface', 'ui', 'ux', 'card', 'cards', 'menu',
    'about', 'contact', 'services', 'service', 'home', 'main', 'header', 'section', 'sections',
    'start building', 'explore platform', 'get started', 'learn more', 'click here',
    'sign up', 'sign in', 'log in', 'login', 'read more', 'buy now', 'contact us',
    'submit', 'subscribe', 'try for free', 'book a demo', 'request demo', 'view all',
    'see more', 'explore more', 'get in touch',
    'generated by nexus ai', 'generated by nexus ai agent', 'nexus ai', 'nexus ai agent',
    'nexus web application', 'nexus'
  ]);

  const candidates: string[] = [];

  // 0. Explicit Project Brand directive in prompt
  const explicitDirectiveMatch = taskGoal.match(/Project Brand \/ Identity:\s*([^\n]+)/i);
  if (explicitDirectiveMatch && explicitDirectiveMatch[1]) {
    const brand = explicitDirectiveMatch[1].trim();
    if (brand && !stopWords.has(brand.toLowerCase())) {
      candidates.push(brand);
      return candidates;
    }
  }

  // 1. Explicit brand declaration patterns (e.g. called NOVARA AI, company called Bean & Brew, for DevForge)
  // Strip folder/directory patterns first so folder names (e.g. 'folder called my-app') are not misidentified as brand names
  const goalWithoutFolder = taskGoal.replace(/(?:in\s+a\s+)?(?:folder|directory|subfolder)\s+(?:called|named)\s+[`"']?[a-zA-Z0-9_\-]+[`"']?/gi, '');

  const namePatterns = [
    /(?:company called|brand called|brand named|for a fictional technology company called|for a fictional ai company called|for an ai company called|for a cafe called|for a company called|for a startup called)\s+[`"']?([a-zA-Z0-9_& -]+?)[`"']?(?:\.|\s+with|\s+that|\s+including|\s+requirements|\s+featuring|\s+and|\s+in\s+a|\s+to|$)/i,
    /(?:called|named)\s+[`"']?([a-zA-Z0-9_& -]+?)[`"']?(?:\.|\s+with|\s+that|\s+including|\s+requirements|\s+featuring|\s+and|\s+in\s+a|\s+to|$)/i,
    /(?:portfolio|landing page|website|web app|app|application)\s+for\s+[`"']?([a-zA-Z0-9_& -]+?)[`"']?(?:\.|\s+with|\s+that|\s+including|\s+requirements|\s+featuring|\s+and|\s+in\s+a|\s+to|$)/i,
    /\bfor\s+[`"']?([A-Z][a-zA-Z0-9_&]+(?:\s+[A-Z][a-zA-Z0-9_&]+)*)[`"']?(?:\.|\s+with|\s+that|\s+including|\s+requirements|\s+featuring|\s+and|\s+in\s+a|\s+to|$)/,
  ];

  for (const pat of namePatterns) {
    const match = goalWithoutFolder.match(pat);
    if (match && match[1]) {
      let val = match[1].trim();
      val = val.replace(/^(?:a|an|the)\s+/i, '').trim();
      if (val.length >= 2 && !stopWords.has(val.toLowerCase()) && !candidates.includes(val)) {
        candidates.push(val);
      }
    }
  }

  // If explicit brand names were identified, return them
  if (candidates.length > 0) {
    return candidates;
  }

  // 2. Match quoted strings e.g. "NEXORA", "Bean & Brew"
  const quotesMatch = taskGoal.match(/"([^"]+)"|'([^']+)'|“([^”]+)”/g);
  if (quotesMatch) {
    for (const q of quotesMatch) {
      const clean = q.replace(/["'“”]/g, '').trim();
      if (clean.length >= 2 && !stopWords.has(clean.toLowerCase()) && !candidates.includes(clean)) {
        candidates.push(clean);
      }
    }
  }

  if (candidates.length > 0) {
    return candidates;
  }

  // 3. Match multi-word capitalized brands or acronyms (e.g., NOVARA AI, NEXORA)
  const multiCapMatch = taskGoal.match(/\b([A-Z][A-Z0-9_-]+(?:\s+[A-Z][A-Z0-9_-]+)+)\b/g);
  if (multiCapMatch) {
    for (const phrase of multiCapMatch) {
      const words = phrase.toLowerCase().split(/\s+/);
      const isAllStopWords = words.every(
        (w) => stopWords.has(w) || /^(html|css|http|url|json|api|cta|faq|todo|tbd|dom|nexus|app|ui|ux|js|ts|task)$/i.test(w)
      );
      if (!isAllStopWords && !candidates.includes(phrase)) {
        candidates.push(phrase);
      }
    }
  }

  if (candidates.length > 0) {
    return candidates;
  }

  // 4. Match single ALL-CAPS acronyms / distinct brand names (e.g., NEXORA, NOVARA)
  const allCapsWords = taskGoal.match(/\b[A-Z0-9_-]{3,}\b/g);
  if (allCapsWords) {
    for (const w of allCapsWords) {
      if (!stopWords.has(w.toLowerCase()) && !candidates.includes(w) && !/^(HTML|CSS|HTTP|URL|JSON|API|CTA|FAQ|TODO|TBD|DOM|NEXUS)$/i.test(w)) {
        candidates.push(w);
      }
    }
  }

  return candidates;
}

/**
 * Extracts requested hero CTA/button or headline terms from parentGoal or unit.
 */
export function extractHeroRequestedTerms(parentGoal: string, unit?: import('./taskDecompositionTypes.js').DecomposedTaskUnit): string[] {
  const terms: string[] = [];

  const unitText = unit ? `${unit.title} ${unit.description} ${unit.expectedOutput} ${unit.verificationCriteria.join(' ')}` : '';
  const combined = `${parentGoal} ${unitText}`;

  // Find quotes near hero / CTA keywords
  const heroMatch = combined.match(/(?:hero|headline|cta\s+buttons?|banner)[^.]*?(?:buttons?|titled|with|saying)?\s*([“"'][^"']+?[”"'](?:\s+and\s+[“"'][^"']+?[”"'])*)/i);
  if (heroMatch && heroMatch[1]) {
    const qMatches = heroMatch[1].match(/["'“”]([^"'“”]+)["'“”]/g);
    if (qMatches) {
      for (const q of qMatches) {
        const clean = q.replace(/["'“”]/g, '').trim();
        if (clean.length >= 2 && !terms.includes(clean)) {
          terms.push(clean);
        }
      }
    }
  }

  // Also check if unit verification criteria explicitly specifies a quoted term
  if (unit) {
    for (const crit of unit.verificationCriteria) {
      const critQuotes = crit.match(/["'“]([^"'“”]+)["'”]/g);
      if (critQuotes) {
        for (const q of critQuotes) {
          const clean = q.replace(/["'“”]/g, '').trim();
          if (clean.length >= 2 && !terms.includes(clean)) {
            terms.push(clean);
          }
        }
      }
    }
  }

  return terms;
}

