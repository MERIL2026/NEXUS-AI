/**
 * Analyzes semantic container elements (<section>, <header>, <nav>, <footer>, <main>, <article>, and major section <div>s)
 * to detect empty shells or comment-only skeletons.
 */
export function detectSkeletonContainers(htmlContent: string): SkeletonDetectionResult {
  const reasons: string[] = [];
  const skeletonSectionNames: string[] = [];

  // Decorative element patterns that are legitimately empty in modern CSS (glows, overlays, bars, etc.)
  const decorativePattern = /(?:bg-glow|bg-grid|overlay|backdrop|particle|spacer|divider|\bbar\b|toggle-bar|separator|decoration|blur|halo|beam|mesh|glow|circle|dot|blob|star|spinner)/i;

  // 1. Check all <section ...>...</section> tags (sections should never be empty or comment-only in complete projects)
  const sectionRegex = /<section\b([^>]*)>([\s\S]*?)<\/section>/gi;
  let totalSections = 0;
  let emptyOrCommentOnlySections = 0;

  let sMatch: RegExpExecArray | null;
  while ((sMatch = sectionRegex.exec(htmlContent)) !== null) {
    totalSections++;
    const attrs = sMatch[1];
    const innerContent = sMatch[2] || '';

    const idMatch = attrs.match(/id=["']([^"']+)["']/i);
    const classMatch = attrs.match(/class=["']([^"']+)["']/i);
    const identifier = idMatch
      ? `#${idMatch[1]}`
      : classMatch
      ? `.${classMatch[1].split(/\s+/)[0]}`
      : `section[${totalSections}]`;

    const trimmedInner = innerContent.trim();
    const visibleText = extractVisibleText(innerContent);
    const isCommentOnly = trimmedInner.length > 0 && /^(\s*<!--[\s\S]*?-->\s*)+$/i.test(trimmedInner);
    const isEmpty = trimmedInner.length === 0;
    const hasVisualElements = /<(?:img|svg|input|button|canvas|video|audio|iframe|form|ul|ol|table|h[1-6]|p)\b/i.test(innerContent);

    if (isCommentOnly || (isEmpty && !decorativePattern.test(identifier)) || (visibleText.length === 0 && !hasVisualElements && !decorativePattern.test(identifier))) {
      emptyOrCommentOnlySections++;
      skeletonSectionNames.push(identifier);
      if (isCommentOnly) {
        reasons.push(`Section <${identifier}> contains only HTML comments without real implementation.`);
      } else if (isEmpty) {
        reasons.push(`Section <${identifier}> is completely empty.`);
      } else {
        reasons.push(`Section <${identifier}> contains no visible text or UI elements.`);
      }
    }
  }

  // 2. Check major content <div id="..." or class="..."> containing comment-only placeholders like <!-- Hero Content -->
  const divCommentRegex = /<div\b[^>]*?(?:id|class)=["']([^"']+)["'][^>]*>\s*<!--\s*([a-zA-Z0-9_\s-]+?)\s*(?:Content|Section|Placeholder)?\s*-->\s*<\/div>/gi;
  let dMatch: RegExpExecArray | null;
  while ((dMatch = divCommentRegex.exec(htmlContent)) !== null) {
    const divIdOrClass = dMatch[1];
    const placeholderText = dMatch[2];
    const identifier = `div.${divIdOrClass}`;
    if (!skeletonSectionNames.includes(identifier)) {
      skeletonSectionNames.push(identifier);
      emptyOrCommentOnlySections++;
      reasons.push(`Container <${identifier}> contains only placeholder comment '<!-- ${placeholderText} -->'`);
    }
  }

  // 3. Determine if document is an incomplete skeleton
  const totalContainers = totalSections + (skeletonSectionNames.length - emptyOrCommentOnlySections);
  const isSkeleton =
    skeletonSectionNames.length > 0 &&
    (emptyOrCommentOnlySections >= 2 ||
      (totalSections > 0 && emptyOrCommentOnlySections / totalSections >= 0.3) ||
      reasons.some((r) => r.includes('contains only HTML comments') || r.includes('placeholder comment')));

  return {
    isSkeleton,
    totalContainers: Math.max(totalContainers, totalSections),
    emptyOrCommentOnlyContainers: emptyOrCommentOnlySections,
    skeletonSectionNames,
    reasons,
  };
}

